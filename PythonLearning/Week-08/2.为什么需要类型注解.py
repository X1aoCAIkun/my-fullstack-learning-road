# 类比：写代码 = 签合同
# 没注解：合同上写“甲方给乙方东西”---给啥？什么时候？数量？全是口头约定，扯皮起步
# 有注解：合同上写“甲方在 2026/11/16 前给乙方 100 个苹果”---一目了然


# 没注解（传错了运行时才报错）
def add1(a, b):
    return a + b

add1("1", 2)         # TypeError

# 有注解（IDE / mypy 提前告诉你错了）
def add2(a: int, b: int) -> int:
    return a + b

add2("1", 2)   # 这里在输完 2 时就会有提示了

# 划重点：Python是 “动态类型” 语言，注解 “不会在运行时检查”（除非使用Pydantic / typeguard ）
# 注解是给 “人和工具看的”