# 正则就像搜索通配符--Python根据用户的描述找出所有匹配的部分
import re       # re是第三方库需要导入


text = "我的电话是13800138000，他的电话是13912345678"
phones = re.findall(r"1[3-9]\d{9}", text)     # findall是将每个匹配结果组合成一个列表
print(phones)           # ['13800138000', '12912345678']

# 常用元字符(通配符属于元字符)
# \d 数字  \w 字母数字下划线  \s 空白
# . 任意字符(不包含换行字符)
# +  1个或多个    *  0个或多个      ? 0或1
# {n} 恰好n个     {n, m} n个到m个
# ^ 匹配行首        $ 匹配行尾
 

# 替换
print(re.sub(r"\d", "*", "abc123"))         # abc***